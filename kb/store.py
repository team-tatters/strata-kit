"""Store contract and the SQLite implementation.

Schema (core/docs/*/kb-engine.md):
  nodes(id, kind, project, path, title, status, updated, revision, payload_json)
  edges(src, dst, kind, confidence, source_ref, created)
  chunks(node_id, seq, heading, text, title, tags, locale, embedding?, meta_json, text_hash)
  embeddings(model, text_hash, dim, vector)        cache, survives rebuild
  baselines(gate, project, key, recorded)
  revisions(store_rev, kit_rev, built_at, sources_hash)

Everything in nodes/edges/chunks is generated by providers and replaced wholesale by
rebuild(); baselines survive a rebuild because they are recorded facts about gates, not
derived views. Nothing in the store is hand-written (rec.kb.generated-views).

Every backend implements the same contract: put_nodes, put_edges, put_chunks, query,
neighbors, search_text, search_vector, rebuild, baselines. The engine never relies on a
backend-specific feature outside the adapter.
"""
from __future__ import annotations

import hashlib
import json
import sqlite3
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Iterable, Iterator, Protocol, Sequence

NODE_KINDS = frozenset({"doc", "code", "decision", "session", "order", "task", "card", "node", "profile"})
EDGE_KINDS = frozenset({"covers", "supersedes", "kb_updates", "orders", "decisions_made", "relay",
                        "calls", "imports", "tests", "member_of", "links",   # links: body wikilink/markdown link (DEC-2026-10-28-07)
                        "implementation"})   # planning → as-built spec, from implementation.spec (DEC-2026-10-29-09)
CONFIDENCE = frozenset({"declared", "extracted", "inferred"})
SCHEMA_VERSION = "3"   # v2: chunks carry heading·title·tags·meta_json, FTS over four columns (DEC-2026-10-28-08)
                       # v3: chunks.text_hash + embeddings cache, vector/hybrid search (DEC-2026-10-28-09)


class StoreError(ValueError):
    """A node, edge or chunk violates the contract (unknown kind, missing id, …)."""


class VectorsUnavailable(NotImplementedError):
    """search_vector called on a backend without a vector index."""


@dataclass(frozen=True)
class Node:
    id: str
    kind: str
    project: str = ""
    path: str = ""
    title: str = ""
    status: str = "active"
    updated: str = ""
    revision: str = ""
    payload: dict = field(default_factory=dict)

    def validate(self) -> None:
        if not self.id:
            raise StoreError("node without id")
        if self.kind not in NODE_KINDS:
            raise StoreError(f"node {self.id}: unknown kind {self.kind!r}")


@dataclass(frozen=True)
class Edge:
    src: str
    dst: str
    kind: str
    confidence: str = "declared"
    source_ref: str = ""
    created: str = ""

    def validate(self) -> None:
        if not self.src or not self.dst:
            raise StoreError(f"edge {self.kind} without endpoints: {self.src!r} -> {self.dst!r}")
        if self.kind not in EDGE_KINDS:
            raise StoreError(f"edge {self.src}->{self.dst}: unknown kind {self.kind!r}")
        if self.confidence not in CONFIDENCE:
            raise StoreError(f"edge {self.src}->{self.dst}: unknown confidence {self.confidence!r}")


@dataclass(frozen=True)
class Chunk:
    """One section of a document. heading/title/tags are denormalized next to the text so the FTS index
    ranks exactly like the legacy index (heading · content · doc_title · doc_tags); meta holds position
    facts (heading_level, line_start, line_end, char_count)."""
    node_id: str
    seq: int
    text: str
    locale: str = ""
    embedding: bytes | None = None
    heading: str = ""
    title: str = ""
    tags: str = ""
    meta: dict = field(default_factory=dict)

    def validate(self) -> None:
        if not self.node_id:
            raise StoreError("chunk without node_id")


@dataclass(frozen=True)
class Hit:
    node: Node
    seq: int
    snippet: str
    rank: float


@dataclass(frozen=True)
class Revision:
    store_rev: str
    kit_rev: str
    built_at: str
    sources_hash: str


class Provider(Protocol):
    """A source that emits generated nodes, edges and chunks. Providers never write directly."""
    name: str

    def collect(self) -> "ProviderOutput": ...


@dataclass
class ProviderOutput:
    nodes: list[Node] = field(default_factory=list)
    edges: list[Edge] = field(default_factory=list)
    chunks: list[Chunk] = field(default_factory=list)


class Store(Protocol):
    def put_nodes(self, nodes: Iterable[Node]) -> int: ...
    def put_edges(self, edges: Iterable[Edge]) -> int: ...
    def put_chunks(self, chunks: Iterable[Chunk]) -> int: ...
    def get(self, node_id: str) -> Node | None: ...
    def query(self, *, kind: str | None = None, project: str | None = None, status: str | None = None,
              path_prefix: str | None = None) -> list[Node]: ...
    def neighbors(self, node_id: str, *, kind: str | None = None, direction: str = "out") -> list[Edge]: ...
    def search_text(self, text: str, *, limit: int = 20, kind: str | None = None,
                    project: str | None = None) -> list[Hit]: ...
    def search_vector(self, embedding: bytes, *, limit: int = 20) -> list[Hit]: ...
    def rebuild(self, providers: Sequence[Provider], *, kit_rev: str = "") -> Revision: ...
    def put_baseline(self, gate: str, project: str, key: str, recorded: str = "") -> None: ...
    def baselines(self, gate: str, project: str | None = None) -> set[str]: ...
    def revision(self) -> Revision | None: ...


# ---------------------------------------------------------------- SQLite

_SCHEMA = f"""
PRAGMA journal_mode = WAL;
CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT);
INSERT OR IGNORE INTO meta VALUES ('schema_version', '{SCHEMA_VERSION}');

CREATE TABLE IF NOT EXISTS nodes (
    id           TEXT PRIMARY KEY,
    kind         TEXT NOT NULL,
    project      TEXT NOT NULL DEFAULT '',
    path         TEXT NOT NULL DEFAULT '',
    title        TEXT NOT NULL DEFAULT '',
    status       TEXT NOT NULL DEFAULT 'active',
    updated      TEXT NOT NULL DEFAULT '',
    revision     TEXT NOT NULL DEFAULT '',
    payload_json TEXT NOT NULL DEFAULT '{{}}'
);
CREATE INDEX IF NOT EXISTS nodes_kind_project ON nodes(kind, project);
CREATE INDEX IF NOT EXISTS nodes_path ON nodes(path);

CREATE TABLE IF NOT EXISTS edges (
    src        TEXT NOT NULL,
    dst        TEXT NOT NULL,
    kind       TEXT NOT NULL,
    confidence TEXT NOT NULL DEFAULT 'declared',
    source_ref TEXT NOT NULL DEFAULT '',
    created    TEXT NOT NULL DEFAULT '',
    PRIMARY KEY (src, dst, kind, source_ref)
);
CREATE INDEX IF NOT EXISTS edges_dst ON edges(dst, kind);

CREATE TABLE IF NOT EXISTS chunks (
    id        INTEGER PRIMARY KEY,
    node_id   TEXT NOT NULL,
    seq       INTEGER NOT NULL,
    heading   TEXT NOT NULL DEFAULT '',
    text      TEXT NOT NULL,
    title     TEXT NOT NULL DEFAULT '',
    tags      TEXT NOT NULL DEFAULT '',
    locale    TEXT NOT NULL DEFAULT '',
    embedding BLOB,
    meta_json TEXT NOT NULL DEFAULT '{{}}',
    text_hash TEXT NOT NULL DEFAULT '',
    UNIQUE (node_id, seq)
);
CREATE INDEX IF NOT EXISTS chunks_node ON chunks(node_id, seq);
CREATE INDEX IF NOT EXISTS chunks_hash ON chunks(text_hash);
-- embedding cache: survives rebuild (like baselines) so vectors are computed once per distinct chunk text
CREATE TABLE IF NOT EXISTS embeddings (
    model     TEXT NOT NULL,
    text_hash TEXT NOT NULL,
    dim       INTEGER NOT NULL,
    vector    BLOB NOT NULL,
    PRIMARY KEY (model, text_hash)
);
CREATE VIRTUAL TABLE IF NOT EXISTS chunks_fts USING fts5(
    heading, text, title, tags, content='chunks', content_rowid='id', tokenize='unicode61');
CREATE TRIGGER IF NOT EXISTS chunks_ai AFTER INSERT ON chunks BEGIN
  INSERT INTO chunks_fts(rowid, heading, text, title, tags) VALUES (new.id, new.heading, new.text, new.title, new.tags);
END;
CREATE TRIGGER IF NOT EXISTS chunks_ad AFTER DELETE ON chunks BEGIN
  INSERT INTO chunks_fts(chunks_fts, rowid, heading, text, title, tags) VALUES ('delete', old.id, old.heading, old.text, old.title, old.tags);
END;
CREATE TRIGGER IF NOT EXISTS chunks_au AFTER UPDATE ON chunks BEGIN
  INSERT INTO chunks_fts(chunks_fts, rowid, heading, text, title, tags) VALUES ('delete', old.id, old.heading, old.text, old.title, old.tags);
  INSERT INTO chunks_fts(rowid, heading, text, title, tags) VALUES (new.id, new.heading, new.text, new.title, new.tags);
END;

CREATE TABLE IF NOT EXISTS baselines (
    gate     TEXT NOT NULL,
    project  TEXT NOT NULL DEFAULT '',
    key      TEXT NOT NULL,
    recorded TEXT NOT NULL DEFAULT '',
    PRIMARY KEY (gate, project, key)
);

CREATE TABLE IF NOT EXISTS revisions (
    store_rev    TEXT NOT NULL,
    kit_rev      TEXT NOT NULL DEFAULT '',
    built_at     TEXT NOT NULL,
    sources_hash TEXT NOT NULL
);
"""


def has_operators(q: str) -> bool:
    return any(tok in ("AND", "OR", "NOT") for tok in q.split())


def fts_query(q: str, any_terms: bool = False) -> str:
    """User text → safe FTS5 MATCH expression (same rule as the legacy kb-search): every token quoted,
    AND/OR/NOT kept as operators, a trailing * kept as a prefix search. any_terms=True joins the tokens with
    OR (bm25 then ranks by how many of them a chunk has) — what a sentence-shaped question needs; it is
    ignored when the user wrote operators."""
    out = []
    for tok in q.split():
        if tok in ("AND", "OR", "NOT"):
            out.append(tok)
            continue
        prefix = tok.endswith("*")
        core = tok.rstrip("*").replace('"', "")
        if core:
            out.append(f'"{core}"*' if prefix else f'"{core}"')
    if any_terms and out and not has_operators(q):
        return " OR ".join(out)
    return " ".join(out)


def embed_text(title: str, heading: str, text: str) -> str:
    """What gets embedded for a chunk: title and heading give the section its context."""
    return "\n".join(x for x in (title or "", heading or "", text or "") if x)


def text_hash(c: Chunk) -> str:
    return hashlib.sha256(embed_text(c.title, c.heading, c.text).encode("utf-8")).hexdigest()


def _now() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


class SqliteStore:
    """Default backend: one file per vault, no server, FTS5 for text. Vectors are not implemented
    here (sqlite-vec adapter pending), so search_vector raises VectorsUnavailable."""

    supports_vectors = False

    def __init__(self, path: str | Path = ":memory:"):
        self.path = Path(path) if path != ":memory:" else None
        if self.path:
            self.path.parent.mkdir(parents=True, exist_ok=True)
            if self.path.is_file() and self._file_schema_version(self.path) != SCHEMA_VERSION:
                # a store is a regenerable cache: an older schema is simply discarded (baselines live in files of record)
                for suffix in ("", "-wal", "-shm"):
                    Path(str(self.path) + suffix).unlink(missing_ok=True)
        self.conn = sqlite3.connect(str(self.path) if self.path else ":memory:")
        self.conn.row_factory = sqlite3.Row
        self.conn.executescript(_SCHEMA)

    @staticmethod
    def _file_schema_version(path: Path) -> str | None:
        try:
            c = sqlite3.connect(str(path))
            try:
                row = c.execute("SELECT value FROM meta WHERE key = 'schema_version'").fetchone()
                return row[0] if row else None
            finally:
                c.close()
        except sqlite3.Error:
            return None

    def close(self) -> None:
        self.conn.close()

    # -- writes ------------------------------------------------------------
    def put_nodes(self, nodes: Iterable[Node]) -> int:
        rows = []
        for n in nodes:
            n.validate()
            rows.append((n.id, n.kind, n.project, n.path, n.title, n.status, n.updated, n.revision,
                         json.dumps(n.payload, ensure_ascii=False, sort_keys=True)))
        with self.conn:
            self.conn.executemany(
                "INSERT OR REPLACE INTO nodes(id, kind, project, path, title, status, updated, revision, payload_json)"
                " VALUES (?,?,?,?,?,?,?,?,?)", rows)
        return len(rows)

    def put_edges(self, edges: Iterable[Edge]) -> int:
        rows = []
        for e in edges:
            e.validate()
            rows.append((e.src, e.dst, e.kind, e.confidence, e.source_ref, e.created))
        with self.conn:
            self.conn.executemany(
                "INSERT OR REPLACE INTO edges(src, dst, kind, confidence, source_ref, created) VALUES (?,?,?,?,?,?)", rows)
        return len(rows)

    def put_chunks(self, chunks: Iterable[Chunk]) -> int:
        rows = [self._chunk_row(c) for c in chunks]
        with self.conn:
            self.conn.executemany("DELETE FROM chunks WHERE node_id = ? AND seq = ?", [(r[0], r[1]) for r in rows])
            self.conn.executemany(
                "INSERT INTO chunks(node_id, seq, heading, text, title, tags, locale, embedding, meta_json, text_hash) VALUES (?,?,?,?,?,?,?,?,?,?)", rows)
        return len(rows)

    @staticmethod
    def _chunk_row(c: Chunk) -> tuple:
        c.validate()
        return (c.node_id, c.seq, c.heading, c.text, c.title, c.tags, c.locale, c.embedding,
                json.dumps(c.meta, ensure_ascii=False, sort_keys=True), text_hash(c))

    @staticmethod
    def _chunk(row: sqlite3.Row) -> Chunk:
        return Chunk(row["node_id"], row["seq"], row["text"], row["locale"], row["embedding"], row["heading"],
                     row["title"], row["tags"], json.loads(row["meta_json"] or "{}"))

    def put_baseline(self, gate: str, project: str, key: str, recorded: str = "") -> None:
        with self.conn:
            self.conn.execute("INSERT OR REPLACE INTO baselines(gate, project, key, recorded) VALUES (?,?,?,?)",
                              (gate, project, key, recorded or _now()))

    # -- reads -------------------------------------------------------------
    @staticmethod
    def _node(row: sqlite3.Row) -> Node:
        return Node(row["id"], row["kind"], row["project"], row["path"], row["title"], row["status"],
                    row["updated"], row["revision"], json.loads(row["payload_json"] or "{}"))

    def get(self, node_id: str) -> Node | None:
        row = self.conn.execute("SELECT * FROM nodes WHERE id = ?", (node_id,)).fetchone()
        return self._node(row) if row else None

    def query(self, *, kind: str | None = None, project: str | None = None, status: str | None = None,
              path_prefix: str | None = None) -> list[Node]:
        where, args = [], []
        for col, val in (("kind", kind), ("project", project), ("status", status)):
            if val is not None:
                where.append(f"{col} = ?")
                args.append(val)
        if path_prefix is not None:
            where.append("path LIKE ? ESCAPE '\\'")
            args.append(path_prefix.replace("%", "\\%").replace("_", "\\_") + "%")
        sql = "SELECT * FROM nodes" + (" WHERE " + " AND ".join(where) if where else "") + " ORDER BY id"
        return [self._node(r) for r in self.conn.execute(sql, args)]

    def neighbors(self, node_id: str, *, kind: str | None = None, direction: str = "out") -> list[Edge]:
        if direction not in ("out", "in", "both"):
            raise StoreError(f"direction must be out|in|both, got {direction!r}")
        cols = {"out": ["src"], "in": ["dst"], "both": ["src", "dst"]}[direction]
        where = " OR ".join(f"{c} = ?" for c in cols)
        args: list = [node_id] * len(cols)
        if kind is not None:
            where = f"({where}) AND kind = ?"
            args.append(kind)
        rows = self.conn.execute(f"SELECT * FROM edges WHERE {where} ORDER BY src, dst, kind, source_ref", args)
        return [Edge(r["src"], r["dst"], r["kind"], r["confidence"], r["source_ref"], r["created"]) for r in rows]

    def chunks_of(self, node_id: str) -> list[Chunk]:
        rows = self.conn.execute("SELECT * FROM chunks WHERE node_id = ? ORDER BY seq", (node_id,))
        return [self._chunk(r) for r in rows]

    def search_text(self, text: str, *, limit: int = 20, kind: str | None = None,
                    project: str | None = None) -> list[Hit]:
        q = fts_query(text)
        if not q:
            return []
        where, args = ["chunks_fts MATCH ?"], [q]
        if kind is not None:
            where.append("n.kind = ?")
            args.append(kind)
        if project is not None:
            where.append("n.project = ?")
            args.append(project)
        args.append(limit)
        sql = ("SELECT n.*, c.seq AS seq, snippet(chunks_fts, 1, '[', ']', '…', 24) AS snippet, bm25(chunks_fts) AS rank"
               " FROM chunks_fts JOIN chunks c ON c.id = chunks_fts.rowid JOIN nodes n ON n.id = c.node_id"
               f" WHERE {' AND '.join(where)} ORDER BY rank, n.id, c.seq LIMIT ?")
        return [Hit(self._node(r), r["seq"], r["snippet"], r["rank"]) for r in self.conn.execute(sql, args)]

    # -- embeddings ----------------------------------------------------------
    def embedding_model(self) -> str | None:
        row = self.conn.execute("SELECT value FROM meta WHERE key = 'embedding_model'").fetchone()
        return row[0] if row else None

    def missing_embeddings(self, model: str) -> list[tuple[str, int, str, str]]:
        """(node_id, seq, text_hash, text_to_embed) for chunks the cache does not cover for this model."""
        rows = self.conn.execute(
            "SELECT c.node_id, c.seq, c.text_hash, c.title, c.heading, c.text FROM chunks c"
            " WHERE NOT EXISTS (SELECT 1 FROM embeddings e WHERE e.model = ? AND e.text_hash = c.text_hash)"
            " GROUP BY c.text_hash ORDER BY c.id", (model,)).fetchall()
        return [(r["node_id"], r["seq"], r["text_hash"], embed_text(r["title"], r["heading"], r["text"])) for r in rows]

    def put_embeddings(self, model: str, vectors: Iterable[tuple[str, "object"]]) -> int:
        """Cache (text_hash, vector) pairs for the model, make it the store's model and attach to chunks."""
        import numpy as np
        rows = []
        for h, v in vectors:
            arr = np.asarray(v, dtype=np.float32).reshape(-1)
            rows.append((model, h, int(arr.shape[0]), arr.tobytes()))
        with self.conn:
            self.conn.executemany("INSERT OR REPLACE INTO embeddings(model, text_hash, dim, vector) VALUES (?,?,?,?)", rows)
            self.conn.execute("INSERT OR REPLACE INTO meta(key, value) VALUES ('embedding_model', ?)", (model,))
            self.conn.execute("UPDATE chunks SET embedding = (SELECT vector FROM embeddings e WHERE e.model = ? AND e.text_hash = chunks.text_hash)", (model,))
        return len(rows)

    def embedding_coverage(self) -> tuple[int, int]:
        with_vec, total = self.conn.execute("SELECT COUNT(embedding), COUNT(*) FROM chunks").fetchone()
        return int(with_vec), int(total)

    def chunk(self, node_id: str, seq: int) -> Chunk | None:
        row = self.conn.execute("SELECT * FROM chunks WHERE node_id = ? AND seq = ?", (node_id, seq)).fetchone()
        return self._chunk(row) if row else None

    # planning: only the refined documents of a bundle are knowledge; originals, source/ and audit/ are evidence (DEC-2026-11-01-04)
    KNOWLEDGE_ONLY_SQL = ("NOT (n.kind IN ('decision', 'order', 'task') AND n.id NOT LIKE 'doc:%')"
                          " AND COALESCE(json_extract(n.payload_json, '$.category'), '') <> 'archive'"
                          " AND NOT (COALESCE(json_extract(n.payload_json, '$.category'), '') = 'planning'"
                          " AND COALESCE(json_extract(n.payload_json, '$.planning_layer'), '') <> 'refined')")

    def _vector_matrix(self, kind: str | None, project: str | None, knowledge_only: bool = False):
        """(ids, node_ids, seqs, matrix) of every embedded chunk, filtered by node kind/project. Brute force is
        the right tool at this scale: 7k × 1024 float32 is 28MB and a query is a few milliseconds."""
        import numpy as np
        where, args = ["c.embedding IS NOT NULL"], []
        if kind is not None:
            where.append("n.kind = ?")
            args.append(kind)
        if project is not None:
            where.append("n.project = ?")
            args.append(project)
        if knowledge_only:
            where.append(self.KNOWLEDGE_ONLY_SQL)
        rows = self.conn.execute(f"SELECT c.id, c.node_id, c.seq, c.embedding FROM chunks c JOIN nodes n ON n.id = c.node_id"
                                 f" WHERE {' AND '.join(where)} ORDER BY c.id", args).fetchall()
        if not rows:
            return [], [], [], None
        mat = np.vstack([np.frombuffer(r["embedding"], dtype=np.float32) for r in rows])
        return [r["id"] for r in rows], [r["node_id"] for r in rows], [r["seq"] for r in rows], mat

    def search_vector(self, embedding, *, limit: int = 20, kind: str | None = None, project: str | None = None,
                      knowledge_only: bool = False) -> list[Hit]:
        """Cosine similarity over cached chunk vectors. Hit.rank is the negative similarity so that, like bm25,
        smaller is better. knowledge_only restricts the candidates to knowledge documents (no sessions · tasks ·
        planning · records) before the top-k cut. Raises VectorsUnavailable when no chunk has an embedding yet."""
        import numpy as np
        ids, node_ids, seqs, mat = self._vector_matrix(kind, project, knowledge_only)
        if mat is None:
            raise VectorsUnavailable("no chunk embeddings in the store yet — run: python3 -m kb embed")
        q = np.asarray(embedding, dtype=np.float32).reshape(-1)
        if q.shape[0] != mat.shape[1]:
            raise StoreError(f"query vector has {q.shape[0]} dims, store has {mat.shape[1]}")
        q = q / (np.linalg.norm(q) or 1.0)
        norms = np.linalg.norm(mat, axis=1)
        norms[norms == 0] = 1.0
        scores = (mat @ q) / norms
        order = np.argsort(-scores, kind="stable")[:limit]
        hits = []
        for i in order:
            node = self.get(node_ids[i])
            c = self.chunk(node_ids[i], seqs[i])
            hits.append(Hit(node, seqs[i], (c.text[:160] if c else ""), float(-scores[i])))
        return hits

    def _fts_ranked(self, text: str, limit: int, kind: str | None, project: str | None,
                    any_terms: bool = False, knowledge_only: bool = False) -> list[tuple[int, str, int, float, str]]:
        q = fts_query(text, any_terms)
        if not q:
            return []
        where, args = ["chunks_fts MATCH ?"], [q]
        if kind is not None:
            where.append("n.kind = ?")
            args.append(kind)
        if project is not None:
            where.append("n.project = ?")
            args.append(project)
        if knowledge_only:
            where.append(self.KNOWLEDGE_ONLY_SQL)
        args.append(limit)
        sql = ("SELECT c.id, c.node_id, c.seq, bm25(chunks_fts) AS rank, snippet(chunks_fts, 1, '[', ']', '…', 24) AS snippet"
               " FROM chunks_fts JOIN chunks c ON c.id = chunks_fts.rowid JOIN nodes n ON n.id = c.node_id"
               f" WHERE {' AND '.join(where)} ORDER BY rank, c.id LIMIT ?")
        return [(r["id"], r["node_id"], r["seq"], r["rank"], r["snippet"]) for r in self.conn.execute(sql, args)]

    def search_hybrid(self, text: str, embedding, *, limit: int = 20, kind: str | None = None, project: str | None = None,
                      k: int = 20, depth: int = 5, fts_weight: float = 0.5, dense_weight: float = 1.0,
                      knowledge_only: bool = False) -> list[Hit]:
        """Reciprocal-rank fusion of the FTS ranking and the vector ranking (each taken to limit*depth).
        Defaults k=20, fts 0.5 · dense 1.0 came out best on the vault's 34-query set (2026-10-28: recall@5 0.85
        vs dense alone 0.82, fts-any 0.67). Hit.rank is the negative RRF score (smaller is better). Falls back to
        FTS alone when no vectors exist."""
        pool = max(limit * depth, limit)
        fts = self._fts_ranked(text, pool, kind, project, any_terms=True, knowledge_only=knowledge_only)   # any term counts, bm25 ranks
        try:
            vec = self.search_vector(embedding, limit=pool, kind=kind, project=project, knowledge_only=knowledge_only)
        except VectorsUnavailable:
            vec = []
        score: dict[tuple[str, int], float] = {}
        snippet: dict[tuple[str, int], str] = {}
        for r, (cid, node_id, seq, _rank, snip) in enumerate(fts):
            score[(node_id, seq)] = score.get((node_id, seq), 0.0) + fts_weight / (k + r + 1)
            snippet[(node_id, seq)] = snip
        for r, h in enumerate(vec):
            key = (h.node.id, h.seq)
            score[key] = score.get(key, 0.0) + dense_weight / (k + r + 1)
            snippet.setdefault(key, h.snippet)
        ranked = sorted(score.items(), key=lambda kv: (-kv[1], kv[0]))[:limit]
        return [Hit(self.get(nid), seq, snippet.get((nid, seq), ""), -s) for (nid, seq), s in ranked]

    def baselines(self, gate: str, project: str | None = None) -> set[str]:
        if project is None:
            rows = self.conn.execute("SELECT key FROM baselines WHERE gate = ?", (gate,))
        else:
            rows = self.conn.execute("SELECT key FROM baselines WHERE gate = ? AND project = ?", (gate, project))
        return {r["key"] for r in rows}

    def revision(self) -> Revision | None:
        row = self.conn.execute("SELECT * FROM revisions ORDER BY rowid DESC LIMIT 1").fetchone()
        return Revision(row["store_rev"], row["kit_rev"], row["built_at"], row["sources_hash"]) if row else None

    def counts(self) -> dict[str, int]:
        out = {}
        for t in ("nodes", "edges", "chunks", "baselines"):
            out[t] = self.conn.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0]
        return out

    # -- rebuild -----------------------------------------------------------
    def rebuild(self, providers: Sequence[Provider], *, kit_rev: str = "") -> Revision:
        """Replace all generated rows with the providers' output in one transaction.
        Baselines are kept. The revision row records what the store was built from."""
        outputs = [(p.name, p.collect()) for p in providers]
        for _, out in outputs:
            for n in out.nodes:
                n.validate()
            for e in out.edges:
                e.validate()
            for c in out.chunks:
                c.validate()
        h = hashlib.sha256()
        for name, out in outputs:
            h.update(name.encode())
            for n in sorted(out.nodes, key=lambda x: x.id):
                h.update(f"{n.id}\0{n.kind}\0{n.revision}\n".encode())
            for e in sorted(out.edges, key=lambda x: (x.src, x.dst, x.kind, x.source_ref)):
                h.update(f"{e.src}\0{e.dst}\0{e.kind}\0{e.source_ref}\n".encode())
        sources_hash = h.hexdigest()
        store_rev = hashlib.sha256(f"{sources_hash}\0{kit_rev}".encode()).hexdigest()[:16]
        rev = Revision(store_rev, kit_rev, _now(), sources_hash)
        cur = self.conn.cursor()
        try:
            cur.execute("BEGIN")
            cur.execute("DELETE FROM chunks")
            cur.execute("DELETE FROM edges")
            cur.execute("DELETE FROM nodes")
            cur.execute("DELETE FROM revisions")
            for _, out in outputs:
                cur.executemany(
                    "INSERT OR REPLACE INTO nodes(id, kind, project, path, title, status, updated, revision, payload_json)"
                    " VALUES (?,?,?,?,?,?,?,?,?)",
                    [(n.id, n.kind, n.project, n.path, n.title, n.status, n.updated, n.revision,
                      json.dumps(n.payload, ensure_ascii=False, sort_keys=True)) for n in out.nodes])
                cur.executemany(
                    "INSERT OR REPLACE INTO edges(src, dst, kind, confidence, source_ref, created) VALUES (?,?,?,?,?,?)",
                    [(e.src, e.dst, e.kind, e.confidence, e.source_ref, e.created) for e in out.edges])
                cur.executemany(
                    "INSERT OR REPLACE INTO chunks(node_id, seq, heading, text, title, tags, locale, embedding, meta_json, text_hash) VALUES (?,?,?,?,?,?,?,?,?,?)",
                    [self._chunk_row(c) for c in out.chunks])
            cur.execute("INSERT INTO revisions(store_rev, kit_rev, built_at, sources_hash) VALUES (?,?,?,?)",
                        (rev.store_rev, rev.kit_rev, rev.built_at, rev.sources_hash))
            model = cur.execute("SELECT value FROM meta WHERE key = 'embedding_model'").fetchone()
            if model:
                cur.execute("UPDATE chunks SET embedding = (SELECT vector FROM embeddings e WHERE e.model = ? AND e.text_hash = chunks.text_hash)"
                            " WHERE embedding IS NULL", (model[0],))
            cur.execute("COMMIT")
        except Exception:
            cur.execute("ROLLBACK")
            raise
        return rev

    # -- graph helpers for search ------------------------------------------
    STATE_TYPES = ("specification", "concept")

    def state_docs_of_node(self, node_id: str) -> list[Node]:
        """Documents that declare this topic node and are its as-built shape (specification · concept)."""
        out = []
        for e in self.neighbors(node_id, kind="member_of", direction="in"):
            n = self.get(e.src)
            if (n and n.id.startswith("doc:") and n.payload.get("type") in self.STATE_TYPES and n.payload.get("indexed")
                    and not n.payload.get("history") and n.payload.get("category") != "planning"):   # knowledge documents only
                out.append(n)
        return out

    def leads_to(self, node_id: str) -> dict[str, list[Node]]:
        """Where a non-knowledge hit points (DEC-2026-10-28-10): documents it updated (kb_updates), decisions it
        made, the as-built documents of its topic nodes, and for records their orders / mirrors."""
        n = self.get(node_id)
        out: dict[str, list[Node]] = {"documents": [], "decisions": [], "state_docs": [], "orders": [], "mirror": []}
        if n is None:
            return out
        seen: set[str] = set()

        def add(bucket: str, m: Node | None):
            if m is not None and m.id not in seen and m.id != node_id:
                seen.add(m.id)
                out[bucket].append(m)

        for e in self.neighbors(node_id, direction="out"):
            if e.kind == "kb_updates":
                add("documents", self.get(e.dst))
            elif e.kind == "decisions_made":
                add("decisions", self.get(e.dst))
            elif e.kind == "orders":
                add("orders", self.get(e.dst))
            elif e.kind == "member_of":
                dst = self.get(e.dst)
                if dst is None:
                    continue
                if dst.kind == "node":
                    for d in self.state_docs_of_node(dst.id):
                        add("state_docs", d)
                elif dst.kind == "order":
                    add("orders", dst)
        if n.kind == "decision":
            mirror = n.payload.get("mirror")
            if mirror:
                add("mirror", self.get(f"doc:{mirror}"))
        return out

    def dangling_edges(self) -> list[Edge]:
        """Edges whose src or dst is not a node — allowed (targets may live in another provider's
        future run) but reported so gates can decide."""
        rows = self.conn.execute(
            "SELECT e.* FROM edges e LEFT JOIN nodes s ON s.id = e.src LEFT JOIN nodes d ON d.id = e.dst"
            " WHERE s.id IS NULL OR d.id IS NULL ORDER BY e.src, e.dst, e.kind")
        return [Edge(r["src"], r["dst"], r["kind"], r["confidence"], r["source_ref"], r["created"]) for r in rows]


def open_store(path: str | Path | None = None) -> SqliteStore:
    """Open the vault's store: explicit path, else $STRATA_VAULT/.kb/store.sqlite."""
    if path is None:
        from . import vault_root
        v = vault_root()
        if v is None:
            raise StoreError("STRATA_VAULT is not set and no store path was given")
        path = v / ".kb" / "store.sqlite"
    return SqliteStore(path)
