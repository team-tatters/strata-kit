"""verify measures the whole inherited guidance chain (MB-strata-kit-2026-004): the user's global CLAUDE.md, every
ancestor directory's CLAUDE.md, and the files they or the project's CLAUDE.md pull in with @path — not only the
project's AGENTS.md and CLAUDE.md."""
import os
import sys
import tempfile
import unittest
from pathlib import Path

KIT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(KIT / "tools"))

import wizard  # noqa: E402


class InheritedChainTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        r = self.root = Path(self.tmp.name).resolve()
        self.home, self.ws, self.project = r / "home", r / "ws", r / "ws" / "proj"
        (self.home / ".claude").mkdir(parents=True); self.project.mkdir(parents=True); (r / "kb").mkdir()
        (self.home / ".claude" / "CLAUDE.md").write_text("global\n")
        (self.ws / "CLAUDE.md").write_text("계약: @AGENTS.md\n용어: @docs/glossary.md\n코드 안은 아님 `@ignored.md`, 메일 a@b.md\n")
        (self.ws / "AGENTS.md").write_text("workspace contract\n")
        (self.ws / "docs").mkdir(); (self.ws / "docs" / "glossary.md").write_text("terms\n")
        (self.ws / "ignored.md").write_text("x\n"); (self.ws / "b.md").write_text("x\n")
        (self.project / "CLAUDE.md").write_text("- KB: @$DEMO_KB/index.md\n- dir: @$DEMO_KB/\n")
        (r / "kb" / "index.md").write_text("kb index\n")
        os.environ["DEMO_KB"] = str(r / "kb")

    def tearDown(self):
        os.environ.pop("DEMO_KB", None)
        self.tmp.cleanup()

    def test_chain(self):
        chain = wizard.inherited_chain(self.project, home=self.home)
        names = [p.relative_to(self.root).as_posix() for p in chain]
        self.assertEqual(names, ["home/.claude/CLAUDE.md", "ws/CLAUDE.md", "ws/AGENTS.md", "ws/docs/glossary.md"])
        self.assertEqual(wizard.env_imports(self.project, chain), ["$DEMO_KB/index.md", "$DEMO_KB/"])   # reported, not counted
        self.assertEqual(sum(chain.values()), sum(p.stat().st_size for p in chain))


if __name__ == "__main__":
    unittest.main()


class VerifyGradesTest(unittest.TestCase):
    """오더 2026.10.29-02 task-02: verify 는 등급으로 판정한다 — 상속 예산 초과는 default(덮어쓰기 파일로 넘어감), 머리말 누락은 block."""

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.project = Path(self.tmp.name).resolve() / "demo"
        (self.project / ".strata" / "kit").mkdir(parents=True)
        (self.project / ".strata" / "kit" / "registry.yaml").write_text("routes: []\n")
        head = "<!-- generated by strata-kit wizard | core_revision: x -->\n"
        const = wizard.load_yaml(KIT / "core" / "constitution" / "constitution.yaml")["constitution"]   # matches the core (order 14)
        musts = f"Constitution: {const['version']}\n## Must cards\n" + "".join(f"- **{c}** — x\n" for c in const["articles"])
        (self.project / "AGENTS.md").write_text(head + musts + "a" * 13000)          # over the 12,288 B budget
        (self.project / "CLAUDE.md").write_text(head + "- Must cards: " + ", ".join(const["articles"]) + "\n")

    def tearDown(self):
        self.tmp.cleanup()

    def test_budget_is_default_and_overridable(self):
        rc, rep = wizard.verify(self.project, KIT)
        self.assertEqual(rc, 2)
        self.assertTrue(any(l.startswith("FAIL   verify budget") for l in rep["grades"]), rep["grades"])
        (self.project / ".strata" / "gate-overrides.yaml").write_text(
            "overrides:\n- {check: verify, key: 'budget*', reason: 지침 축소 대기, until: 2999-01-01}\n")
        rc, rep = wizard.verify(self.project, KIT)
        self.assertEqual(rc, 0, rep["grades"])
        self.assertTrue(any(l.startswith("pass   verify budget") for l in rep["grades"]))

    def test_missing_revision_header_blocks_even_with_override(self):
        (self.project / "CLAUDE.md").write_text("# hand\n")
        (self.project / ".strata" / "gate-overrides.yaml").write_text(
            "overrides:\n- {check: verify, key: '*', reason: x, until: 2999-01-01}\n")
        rc, rep = wizard.verify(self.project, KIT)
        self.assertEqual(rc, 2)
        self.assertIn("BLOCK  verify revision_header:CLAUDE.md — 생성본 머리말(core_revision) 없음", rep["grades"])


class DiagnoseBudgetTest(unittest.TestCase):
    """MB-strata-kit-2026-031: diagnose counted the embedded decision index and constraint registry as always loaded
    (strata-kit: 28,649 B, budget_ok false) while verify — and the harness — load only AGENTS.md and CLAUDE.md."""

    def test_diagnose_counts_what_verify_counts(self):
        with tempfile.TemporaryDirectory() as t:
            p = Path(t) / "demo"
            (p / ".strata" / "decisions").mkdir(parents=True)
            (p / ".strata" / "profile.yaml").write_text("profile: embedded\nproject: demo\n")
            (p / ".strata" / "decisions.yaml").write_text("x" * 20000)
            (p / ".strata" / "constraint-registry.yaml").write_text("y" * 3000)
            (p / "AGENTS.md").write_text("a" * 6000)
            (p / "CLAUDE.md").write_text("c" * 1500)
            d = wizard.diagnose(p, KIT)
            self.assertEqual(d["always_loaded_bytes"], {"AGENTS.md": 6000, "CLAUDE.md": 1500})
            self.assertTrue(d["budget_ok"])
            self.assertEqual(d["always_loaded_bytes"], wizard.always_loaded(p))


class MemoryIndexTest(VerifyGradesTest):
    """DEC-2026-10-31-19: the memory index the harness loads at every start is shown and warned over 12 KB, never failed."""

    def test_memory_index_warns_without_failing(self):
        from unittest import mock
        (self.project / "AGENTS.md").write_text((self.project / "AGENTS.md").read_text()[:2000])   # back under budget
        home = Path(self.tmp.name) / "home"
        slug = "".join(c if c.isalnum() else "-" for c in str(self.project))
        mem = home / ".claude" / "projects" / slug / "memory"; mem.mkdir(parents=True)
        (mem / "MEMORY.md").write_text("x" * 13000)
        with mock.patch.object(Path, "home", return_value=home):
            rc0, rep = wizard.verify(self.project, KIT)
        self.assertEqual(rep["memory_index_bytes"], 13000)
        self.assertIn("warning", rep["memory_index"])
        self.assertFalse(any("memory" in l for l in rep["grades"]))              # not a graded finding
