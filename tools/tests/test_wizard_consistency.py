class ConditionalMustTest(unittest.TestCase):
    """DEC-2026-10-30-01: conditional musts load from facts without a question; opt-in defaults may follow a fact;
    a decline keeps its reason."""
    GV, LC, OR = "rec.kb.generated-views", "rec.kb.link-currency", "rec.decision.orchestrator-decisions-flow-to-records"
    CO, MIN = "rec.kb.covers-owner", "rec.placement.minimal-strata-in-code-repo"

    def setUp(self):
        import os
        self.tmp = tempfile.TemporaryDirectory()
        self.project = Path(self.tmp.name) / "demo"; self.project.mkdir()
        os.environ["STRATA_USER_CONFIG"] = str(Path(self.tmp.name) / "none.yaml")

    def tearDown(self):
        import os
        os.environ.pop("STRATA_USER_CONFIG", None); self.tmp.cleanup()

    def rec(self, domain="personal", answers=None, **facts):
        p = wizard.recommend(self.project, KIT, "core.generic", {}, "ko", domain, answers, None, facts)
        return p, {c["id"] for c in p["cards"] if c["strength"] == "must"}

    def test_conditions_and_defaults(self):
        p, musts = self.rec(uses_vault=True, uses_quilt=False)
        self.assertTrue({self.GV, self.LC, self.CO} <= musts)
        self.assertNotIn(self.OR, musts); self.assertNotIn(self.MIN, musts)
        self.assertEqual({c["id"]: c["on"] for c in p["conditional"]}[self.OR], False)
        self.assertEqual(next(a for a in p["adoption"] if a["id"] == self.CO)["default_from"], "fact:uses_vault")
        p, musts = self.rec(domain="work", uses_vault=False, uses_quilt=True)
        self.assertIn(self.OR, musts); self.assertIn(self.MIN, musts)
        self.assertFalse({self.GV, self.LC, self.CO} & musts)

    def test_decline_keeps_reason(self):
        p, musts = self.rec(answers={self.CO: (False, "문서화 범위 밖 PoC"), self.MIN: (False, None)}, uses_vault=True)
        self.assertNotIn(self.CO, musts)
        self.assertEqual(next(a for a in p["adoption"] if a["id"] == self.CO)["declined_reason"], "문서화 범위 밖 PoC")
        self.assertTrue(any(self.MIN in w for w in p["warnings"]))
        p["approved"] = True
        (self.project / ".strata" / "kit").mkdir(parents=True)
        (self.project / ".strata" / "kit" / "proposal.yaml").write_text(yaml.safe_dump(p, allow_unicode=True), encoding="utf-8")
        wizard.generate(self.project, KIT, apply=True)
        reg = yaml.safe_load((self.project / ".strata" / "kit" / "registry.yaml").read_text(encoding="utf-8"))
        self.assertIn({"id": self.CO, "reason": "문서화 범위 밖 PoC"}, reg["declined"])
        self.assertIn(self.GV, reg["conditional"]); self.assertIn(self.GV, reg["must_cards"])
        self.assertEqual(wizard.verify(self.project, KIT)[1]["constitution:AGENTS.md"], "ok")

    def test_facts_persist_from_the_last_proposal(self):
        (self.project / ".strata" / "kit").mkdir(parents=True)
        (self.project / ".strata" / "kit" / "proposal.yaml").write_text("facts: {uses_vault: false, uses_quilt: true}\n", encoding="utf-8")
        f = wizard.project_facts(self.project, "personal")
        self.assertEqual((f["uses_vault"], f["uses_quilt"], f["domain_work"]), (False, True, False))


