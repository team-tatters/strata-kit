class OptInAdoptionTest(unittest.TestCase):
    """DEC-2026-10-29-14: opt-in must cards are asked; the default comes from the user's list, then the profile."""
    SD, WT = "rec.data.soft-delete-only", "rec.workflow.worktree-only-with-consent"

    def setUp(self):
        import os
        self.tmp = tempfile.TemporaryDirectory()
        self.project = Path(self.tmp.name) / "demo"; self.project.mkdir()
        self.cfg = Path(self.tmp.name) / "config.yaml"
        os.environ["STRATA_USER_CONFIG"] = str(self.cfg)

    def tearDown(self):
        import os
        os.environ.pop("STRATA_USER_CONFIG", None)
        self.tmp.cleanup()

    def adoption(self, profile="core.generic", answers=None):
        p = wizard.recommend(self.project, KIT, profile, {}, "ko", "personal", answers)
        return {a["id"]: a for a in p["adoption"]}, {c["id"] for c in p["cards"] if c["strength"] == "must"}

    def test_not_articles_and_off_without_defaults(self):
        self.assertNotIn(self.SD, CONST["articles"]); self.assertNotIn(self.WT, CONST["articles"])
        ad, musts = self.adoption()
        self.assertFalse(ad[self.SD]["adopted"]); self.assertFalse(ad[self.WT]["adopted"])
        self.assertNotIn(self.SD, musts)
        self.assertIn("채택", ad[self.SD]["question"])

    def test_user_list_and_profile_default_turn_it_on(self):
        self.cfg.write_text("wizard:\n  adopt_cards: [rec.workflow.worktree-only-with-consent]\n", encoding="utf-8")
        ad, musts = self.adoption("backend.go-service")
        self.assertEqual((ad[self.WT]["adopted"], ad[self.WT]["default_from"]), (True, "user"))
        self.assertEqual((ad[self.SD]["adopted"], ad[self.SD]["default_from"]), (True, "profile"))
        self.assertTrue({self.SD, self.WT} <= musts)

    def test_answer_overrides_default(self):
        ad, musts = self.adoption("backend.go-service", {self.SD: False, self.WT: True})
        self.assertFalse(ad[self.SD]["adopted"]); self.assertIn(self.WT, musts); self.assertNotIn(self.SD, musts)

    def test_header_names_adopted_and_missing(self):
        line = wizard.musts_line({"must_cards": CONST["articles"][1:] + [self.WT]}, CONST)
        self.assertIn("adopted: " + self.WT, line)
        self.assertIn("MISSING from generated guidance: " + CONST["articles"][0], line)


