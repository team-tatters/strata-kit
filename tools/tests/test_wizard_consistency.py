import sys
import tempfile
import unittest
from pathlib import Path

import yaml

KIT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(KIT / "tools"))

import wizard  # noqa: E402

CONST = yaml.safe_load((KIT / "core" / "constitution" / "constitution.yaml").read_text(encoding="utf-8"))["constitution"]
MARK = "<!-- generated by strata-kit wizard | core_revision: x | adapter_revision: y | profile: core.generic | 2026-10-29 -->"


def agents(version: str, ids: list[str]) -> str:
    return "\n".join([MARK, "# demo", "", f"Profile: `core.generic` · Domain: `personal` · Constitution: {version}", "",
                      "## Must cards (never waived)", ""] + [f"- **{i}** — x" for i in ids] + ["", "## Should cards", "", "- **rec.s** — s", ""])


class ConstitutionCheckTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.project = Path(self.tmp.name) / "demo"
        (self.project / ".strata" / "kit").mkdir(parents=True)
        (self.project / ".strata" / "profile.yaml").write_text("profile: embedded\nproject: demo\n", encoding="utf-8")
        (self.project / ".strata" / "kit" / "registry.yaml").write_text("routes: []\n", encoding="utf-8")

    def tearDown(self):
        self.tmp.cleanup()

    def write(self, version, ids, claude_ids=None):
        (self.project / "AGENTS.md").write_text(agents(version, ids), encoding="utf-8")
        (self.project / "CLAUDE.md").write_text(MARK + "\n# demo\n\n- Must cards: " + ", ".join(claude_ids if claude_ids is not None else ids) + "\n", encoding="utf-8")

    def test_matching_guidance_is_ok(self):
        self.write(CONST["version"], CONST["articles"] + ["rec.extra.adopted"])
        _, rep = wizard.verify(self.project, KIT)
        self.assertEqual(rep["constitution:AGENTS.md"], "ok")
        self.assertEqual(rep["constitution:CLAUDE.md"], "ok")

    def test_old_version_and_missing_must_are_reported(self):
        self.write("0.9.0", CONST["articles"][:-1])
        _, rep = wizard.verify(self.project, KIT)
        self.assertIn("constitution 0.9.0", rep["constitution:AGENTS.md"])
        self.assertIn(CONST["articles"][-1], rep["constitution:AGENTS.md"])
        self.assertIn(CONST["articles"][-1], rep["constitution:CLAUDE.md"])
        self.assertTrue(any("constitution:AGENTS.md" in g for g in rep["grades"]), rep["grades"])

    def test_adopted_must_missing_from_guidance_is_reported(self):
        """DEC-2026-10-29-19: a must card the project adopted is part of the approved set, not only the articles."""
        (self.project / ".strata" / "kit" / "registry.yaml").write_text(
            yaml.safe_dump({"must_cards": CONST["articles"] + ["rec.data.soft-delete-only"]}), encoding="utf-8")
        self.write(CONST["version"], CONST["articles"])
        rc, rep = wizard.verify(self.project, KIT)
        self.assertIn("rec.data.soft-delete-only", rep["constitution:AGENTS.md"])
        self.assertEqual(rc, 2)
        self.write(CONST["version"], CONST["articles"] + ["rec.data.soft-delete-only"])
        self.assertEqual(wizard.verify(self.project, KIT)[1]["constitution:AGENTS.md"], "ok")

    def test_handwritten_guidance_is_skipped(self):
        (self.project / "AGENTS.md").write_text("# hand-written\n", encoding="utf-8")
        self.assertNotIn("AGENTS.md", wizard.guidance_musts(self.project))

    def test_entry_path_is_reported(self):
        self.write(CONST["version"], CONST["articles"])
        _, rep = wizard.verify(self.project, KIT)
        self.assertEqual(len(rep["entry_path"]), 3)
        self.assertGreater(rep["entry_path_total"], 0)
        self.assertLess(rep["entry_path_with_header"], rep["entry_path_total"])


class StaleProposalTest(unittest.TestCase):
    def test_generate_refuses_old_constitution(self):
        with tempfile.TemporaryDirectory() as d:
            project = Path(d) / "demo"; (project / ".strata" / "kit").mkdir(parents=True)
            (project / ".strata" / "kit" / "proposal.yaml").write_text(yaml.safe_dump(
                {"project": "demo", "profile": "core.generic", "constitution_version": "0.9.0", "cards": [], "approved": True}), encoding="utf-8")
            with self.assertRaises(SystemExit) as e:
                wizard.generate(project, KIT, apply=True)
            self.assertIn("stale", str(e.exception))


