"""wizard generate keeps hand-written files (MB-strata-kit-2026-010): a file without the wizard's generated marker is
not replaced unless the proposal names it in overwrite_handwritten."""
import sys
import tempfile
import unittest
from pathlib import Path

import yaml

KIT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(KIT / "tools"))

import wizard  # noqa: E402

CORE_VERSION = yaml.safe_load((KIT / "core" / "constitution" / "constitution.yaml").read_text(encoding="utf-8"))["constitution"]["version"]


def proposal(**extra) -> dict:
    p = {"project": "demo", "domain": "personal", "profile": "core.generic", "locale": "ko", "constitution_version": CORE_VERSION,
         "cards": [{"id": "rec.x", "strength": "must", "title": "X", "claim": "x"}], "waived": [], "approved": True,
         "write_paths": ["AGENTS.md", "CLAUDE.md", ".strata/kit/quilt-piece.ko.md"]}
    p.update(extra)
    return p


class GenerateKeepsHandwrittenTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.project = Path(self.tmp.name) / "demo"
        (self.project / ".strata" / "kit").mkdir(parents=True)
        (self.project / "AGENTS.md").write_text("# Vault — Agent Entry\n\n손으로 쓴 지침\n", encoding="utf-8")

    def tearDown(self):
        self.tmp.cleanup()

    def run_generate(self, **extra) -> list[str]:
        (self.project / ".strata" / "kit" / "proposal.yaml").write_text(yaml.safe_dump(proposal(**extra), allow_unicode=True), encoding="utf-8")
        return wizard.generate(self.project, KIT, apply=True)

    def test_handwritten_file_is_kept_and_others_written(self):
        out = self.run_generate()
        self.assertEqual((self.project / "AGENTS.md").read_text(encoding="utf-8"), "# Vault — Agent Entry\n\n손으로 쓴 지침\n")
        self.assertTrue(any(l.startswith("kept hand-written AGENTS.md") for l in out), out)
        self.assertTrue((self.project / "CLAUDE.md").read_text(encoding="utf-8").startswith("<!-- generated by strata-kit wizard"))
        self.assertTrue((self.project / ".strata" / "kit" / "quilt-piece.ko.md").is_file())

    def test_overwrite_handwritten_names_the_file(self):
        self.run_generate(overwrite_handwritten=["AGENTS.md"])
        self.assertTrue((self.project / "AGENTS.md").read_text(encoding="utf-8").startswith("<!-- generated by strata-kit wizard"))

    def test_generated_file_is_regenerated(self):
        (self.project / "AGENTS.md").write_text("<!-- generated by strata-kit wizard | old -->\n# old\n", encoding="utf-8")
        self.run_generate()
        self.assertNotIn("| old -->", (self.project / "AGENTS.md").read_text(encoding="utf-8"))


if __name__ == "__main__":
    unittest.main()


class TierFilesStatedTest(unittest.TestCase):
    """Order 2026.10.29-11: the generated guidance names only the Tier P files that exist (strata-kit's AGENTS.md said
    constraint-registry.yaml and layer-map.yaml were tracked when only decisions/ was)."""

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.project = Path(self.tmp.name) / "demo"
        (self.project / ".strata" / "kit").mkdir(parents=True)
        (self.project / ".strata" / "decisions").mkdir()

    def tearDown(self):
        self.tmp.cleanup()

    def generated(self) -> str:
        (self.project / ".strata" / "kit" / "proposal.yaml").write_text(yaml.safe_dump(proposal(), allow_unicode=True), encoding="utf-8")
        wizard.generate(self.project, KIT, apply=True)
        return (self.project / "AGENTS.md").read_text(encoding="utf-8") + (self.project / "CLAUDE.md").read_text(encoding="utf-8")

    def test_only_existing_files_are_named(self):
        text = self.generated()
        self.assertIn(".strata/decisions/", text)
        self.assertNotIn("layer-map.yaml", text)
        self.assertNotIn("constraint-registry.yaml", text)

    def test_existing_registry_is_named(self):
        (self.project / ".strata" / "constraint-registry.yaml").write_text("constraints: []\n", encoding="utf-8")
        text = self.generated()
        self.assertIn("constraint-registry.yaml", text)
        self.assertNotIn("layer-map.yaml", text)
