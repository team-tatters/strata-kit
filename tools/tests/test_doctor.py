def git(cwd, *a):
    subprocess.run(["git", "-C", str(cwd), "-c", "user.name=t", "-c", "user.email=t@t", *a], check=True, capture_output=True)


def rec(d: Path, rid, tier, affects, supersedes=()):
    (d / f"{rid}-x.yaml").write_text(json.dumps({"decision": {"id": rid, "verification_tier": tier, "affects": affects,
                                                             "supersedes": list(supersedes)}}), encoding="utf-8")


class DoctorTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        r = Path(self.tmp.name).resolve()
        self.vault, self.project = r / "vault", r / "demo"
        (self.vault / "projects" / "demo").mkdir(parents=True)
        (self.project / ".strata" / "decisions").mkdir(parents=True)
        (self.project / ".strata" / "kit").mkdir()
        (self.project / ".strata" / "kit" / "registry.yaml").write_text("routes: []\n")
        self.profile("frontend.next-web")
        (self.project / "CLAUDE.md").write_text("<!-- generated by strata-kit wizard | core_revision: deadbeef0000 -->\n# demo\n")
        git(self.project, "init", "-q"); git(self.project, "add", "-A"); git(self.project, "commit", "-q", "-m", "base")
        self.env = mock.patch.dict(os.environ, {"STRATA_VAULT": str(self.vault)}); self.env.start()
        self.lib = r / "librarian.log"

    def tearDown(self):
        self.env.stop()
        self.tmp.cleanup()

    def profile(self, kit_profile):
        (self.project / ".strata" / "profile.yaml").write_text(f"profile: embedded\nproject: demo\nkit_profile: {kit_profile}\n")

    def run_doctor(self, checks=doctor.PROJECT_CHECKS, today=None):
        return doctor.run(self.project, librarian_log=self.lib, librarian_label="x.none", launchctl="/nonexistent",
                          vault=self.vault, checks=checks, today=today)

    def items(self, res, check=None):
        return [i for i in res["items"] if check is None or i["check"] == check]

    # acceptance 1·4·10 — every item has evidence and a fix, nothing changes, json is the same list as the text
    def test_every_item_has_evidence_and_fix_and_nothing_changes(self):
        def snap():
            st = subprocess.run(["git", "-C", str(self.project), "status", "--porcelain", "--untracked-files=all"], capture_output=True, text=True).stdout
            # SQLite's shared-memory file (-shm) moves on any read in WAL mode; the store's content file must not
            files = {str(p): p.stat().st_mtime_ns for root in (self.project / ".strata", self.vault) for p in root.rglob("*")
                     if p.is_file() and not p.name.endswith(("-shm", "-wal"))}
            return st, files
        from kb.providers import VaultScanner
        from kb.store import SqliteStore
        (self.vault / "projects" / "demo" / "a.md").write_text("---\ntitle: A\nid: kb-demo-a\ntype: concept\nproject: demo\n---\n# A\n[[missing]]\n")
        st = SqliteStore(self.vault / ".kb" / "store.sqlite"); st.rebuild([VaultScanner(self.vault)], kit_rev="t"); st.close()
        os.utime(self.vault / "projects" / "demo" / "a.md")                    # a source newer than the store: stale, not rebuilt
        before = snap()
        res = self.run_doctor()
        self.assertEqual(snap(), before)
        self.assertTrue(any(i["key"] == "store_age" for i in res["items"]))
        self.assertTrue(res["items"])
        for i in res["items"]:
            self.assertTrue(i["evidence"] and i["fix"], i)
        text = doctor.render(res)
        for _, title in doctor.GROUPS:
            self.assertIn(title, text)
        self.assertEqual(text.count("    근거:"), len(res["items"]))
        out = io.StringIO()
        with redirect_stdout(out):
            rc = doctor.main([str(self.project), "--json", "--librarian-log", str(self.lib), "--librarian-label", "x.none"])
        self.assertEqual(rc, json.loads(out.getvalue())["rc"])

    # acceptance 2 — existing grades kept, the ungraded checks graded here
    def test_grades_of_existing_checks(self):
        found = [Finding("verify", "project_registry", "block", "x"), Finding("verify", "budget", "default", "y")]
        with mock.patch("wizard.verify", return_value=(2, {"_findings": found})):
            got = {(i["key"], i["grade"]) for i in self.items(self.run_doctor(checks=(("verify", doctor.check_verify),)), "verify")}
        self.assertEqual(got, {("project_registry", "block"), ("budget", "default")})
        with mock.patch("kb.gates.links.check", return_value=[{"k": 1}]), mock.patch("kb.gates.links.blocking", return_value=True), \
                mock.patch("kb.gates.links.key_of", return_value="projects/demo/a.md→b"):
            (li,) = doctor.check_links(self.project, store=object(), vault=self.vault)
        self.assertEqual(li.grade, "default")
        with mock.patch("kb.gates.hygiene.report", return_value={"summary": {"broken": {"body": 2}}}):
            (hy,) = doctor.check_hygiene(self.project, store=object(), vault=self.vault)
        self.assertEqual(hy.grade, "advisory")
        rec(self.project / ".strata" / "decisions", "DEC-2026-10-31-01", "solo", ["x"])
        (un,) = doctor.check_uncommitted(self.project)
        self.assertEqual((un.grade, un.key), ("default", "uncommitted"))

    # acceptance 3 — a live override passes a default item, an expired one does not
    def test_overrides(self):
        fake = (("fake", lambda p, **_: [doctor.Item("fake", "k", "default", "m", "e", "f")]),)
        self.assertEqual(self.run_doctor(checks=fake)["rc"], 2)
        ov = self.project / ".strata" / "gate-overrides.yaml"
        ov.write_text("overrides:\n- {check: fake, key: k, reason: 대기, until: 2999-01-01}\n")
        res = self.run_doctor(checks=fake)
        (i,) = self.items(res, "fake")
        self.assertEqual((res["rc"], i["status"], i["override"]["reason"]), (0, "overridden", "대기"))
        ov.write_text("overrides:\n- {check: fake, key: k, reason: 지남, until: 2000-01-01}\n")
        res = self.run_doctor(checks=fake)
        (i,) = self.items(res, "fake")
        self.assertEqual((res["rc"], i["status"], i["override"].get("expired")), (2, "unresolved", True))
        self.assertIn("기한 지난 덮어쓰기: 지남", doctor.render(res))

