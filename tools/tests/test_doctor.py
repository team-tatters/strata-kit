    # acceptance 9 — librarian from the log's last run and launchd, unknown when it cannot see
    def test_librarian(self):
        items = doctor.check_librarian(self.lib, "x", "/nonexistent")
        self.assertIn("확인할 수 없습니다", items[0].message)
        self.lib.write_text("=== strata-librarian start 2026-10-30T00:00:00Z kit a ===\nTraceback (most recent call last):\n=== strata-librarian end 2026-10-30T00:01:00Z failed 1: views ===\n"
                            "=== strata-librarian start 2026-10-31T00:00:00Z kit b ===\nok\n=== strata-librarian end 2026-10-31T00:01:00Z failed 0 ===\n")
        fake = Path(self.tmp.name) / "launchctl"; fake.write_text("#!/bin/sh\necho 'runs = 3'\necho 'last exit code = 1'\n"); fake.chmod(0o755)
        log, job = doctor.check_librarian(self.lib, "x", str(fake))
        self.assertIn("오류 줄 없음", log.message)                              # the earlier run's Traceback is not the last run
        self.assertIn("failed 0", log.evidence)
        self.assertIn("마지막 종료 코드 1", job.message)
        self.assertTrue(log.machine and job.machine)
        fake_only = (("fake", lambda p, **_: []),)
        self.assertEqual(self.run_doctor(checks=fake_only)["rc"], 0)           # machine items never change the exit code

    # acceptance 11 — a failing check is shown and the others still run
    def test_a_failing_check_does_not_stop_the_rest(self):
        def boom(p, **_):
            raise RuntimeError("부서짐")
        res = self.run_doctor(checks=(("boom", boom), ("solo_decisions", doctor.check_solo_decisions), ("guidance", doctor.check_guidance_lag)))
        (f,) = self.items(res, "boom")
        self.assertEqual((f["grade"], f["status"]), ("default", "unresolved"))
        self.assertIn("부서짐", f["message"])
        self.assertTrue(self.items(res, "guidance"))                            # ran after the failure
        self.assertEqual(res["rc"], 2)


